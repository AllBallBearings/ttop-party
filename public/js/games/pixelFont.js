/** Width in canvas pixels of `text` at `scale` (6 cells per glyph incl. spacing). */
export function pixelTextWidth(text, scale) {
  return Math.max(0, String(text).length * 6 - 1) * scale;
}

/**
 * Draw `text` with its top-left at (x, y). `shadow` draws a 1-cell drop
 * shadow down-right in that color first, for the classic arcade look.
 */
export function drawPixelText(ctx, text, x, y, scale, color, shadow = null) {
  const str = String(text).toUpperCase();
  const pass = (ox, oy, c) => {
    ctx.fillStyle = c;
    for (let i = 0; i < str.length; i++) {
      const rows = G[str[i]];
      if (!rows) continue;
      for (let ry = 0; ry < 5; ry++) {
        for (let rx = 0; rx < 5; rx++) {
          if (rows[ry][rx] === '1') {
            ctx.fillRect(x + ox + (i * 6 + rx) * scale, y + oy + ry * scale, scale, scale);
          }
        }
      }
    }
  };
  if (shadow) pass(scale, scale, shadow);
  pass(0, 0, color);
}

/** Draw `text` centred on (cx, cy). */
export function drawPixelTextCentered(ctx, text, cx, cy, scale, color, shadow = null) {
  const w = pixelTextWidth(text, scale);
  drawPixelText(ctx, text, Math.round(cx - w / 2), Math.round(cy - (5 * scale) / 2), scale, color, shadow);
}
